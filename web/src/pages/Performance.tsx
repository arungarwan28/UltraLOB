import { useState } from 'react';
import { Panel, StatTile } from '../components/Panel';
import { LatencyChart } from '../components/LatencyChart';
import { compact, formatDuration, formatInt, formatLatency } from '../lib/format';
import type { EngineClient } from '../hooks/useEngine';
import type { BenchResult, NativeBenchmark, Workload } from '../lib/types';
import nativeBenchmark from '../data/native-benchmark.json';

const WORKLOADS: { value: Workload; label: string }[] = [
  { value: 0, label: 'balanced' },
  { value: 1, label: 'cancel heavy' },
  { value: 2, label: 'burst' },
];

const EVENT_CHOICES = [100_000, 500_000, 1_000_000, 2_000_000];

export function PerformancePage({ engine }: { engine: EngineClient }) {
  const [workload, setWorkload] = useState<Workload>(0);
  const [events, setEvents] = useState(1_000_000);
  const [seed, setSeed] = useState('2024');
  const [running, setRunning] = useState(false);
  const [runs, setRuns] = useState<BenchResult[]>([]);

  const native = nativeBenchmark as unknown as NativeBenchmark;

  const run = async () => {
    setRunning(true);
    try {
      const result = await engine.request<BenchResult>({
        type: 'benchmark',
        events,
        seed: Number(seed) || 2024,
        workload,
      });
      setRuns((previous) => [result, ...previous].slice(0, 6));
    } finally {
      setRunning(false);
    }
  };

  const latest = runs[0];

  return (
    <div className="flex flex-col gap-4">
      <div className="grid grid-cols-1 gap-4 xl:grid-cols-[380px_minmax(0,1fr)]">
        <div className="flex flex-col gap-4">
          <Panel title="Run benchmark" hint="executes inside the WASM worker">
            <div className="flex flex-col gap-3">
              <label className="flex flex-col gap-1">
                <span className="text-[10px] uppercase tracking-[0.14em] text-fog">workload</span>
                <div className="grid grid-cols-3 gap-1 rounded-lg border border-line bg-ink p-1">
                  {WORKLOADS.map((option) => (
                    <button
                      key={option.value}
                      type="button"
                      onClick={() => setWorkload(option.value)}
                      className={`rounded-md px-1.5 py-1.5 text-[10px] font-semibold uppercase tracking-[0.1em] ${
                        workload === option.value
                          ? 'bg-panel-2 text-mint'
                          : 'text-fog hover:text-mist'
                      }`}
                    >
                      {option.label}
                    </button>
                  ))}
                </div>
              </label>

              <label className="flex flex-col gap-1">
                <span className="text-[10px] uppercase tracking-[0.14em] text-fog">events</span>
                <div className="grid grid-cols-4 gap-1 rounded-lg border border-line bg-ink p-1">
                  {EVENT_CHOICES.map((choice) => (
                    <button
                      key={choice}
                      type="button"
                      onClick={() => setEvents(choice)}
                      className={`rounded-md px-1 py-1.5 text-[10px] font-semibold ${
                        events === choice ? 'bg-panel-2 text-chalk' : 'text-fog hover:text-mist'
                      }`}
                    >
                      {compact(choice)}
                    </button>
                  ))}
                </div>
              </label>

              <label className="flex flex-col gap-1">
                <span className="text-[10px] uppercase tracking-[0.14em] text-fog">
                  random seed (reproducibility)
                </span>
                <input
                  value={seed}
                  onChange={(event) => setSeed(event.target.value)}
                  inputMode="numeric"
                  className="num rounded-lg border border-line bg-ink px-3 py-2 text-sm text-chalk outline-none focus:border-mint/60"
                />
              </label>

              <button
                type="button"
                onClick={() => void run()}
                disabled={running}
                className={`rounded-lg px-3 py-2.5 text-[11px] font-semibold uppercase tracking-[0.16em] transition-colors ${
                  running
                    ? 'bg-panel-2 text-fog'
                    : 'bg-mint/15 text-mint ring-1 ring-mint/40 hover:bg-mint/20'
                }`}
              >
                {running ? 'measuring…' : 'run benchmark'}
              </button>

              <p className="text-[10px] leading-relaxed text-fog/70">
                Synthetic messages generated by the C++ feed generator and applied through the
                same event processor the terminal uses. Per-event samples include timer
                overhead; the throughput figure is end-to-end and therefore includes feed
                generation.
              </p>
            </div>
          </Panel>

          <Panel title="In-browser results" bodyClassName="p-3">
            {runs.length === 0 ? (
              <div className="py-4 text-center text-[11px] text-fog/60">no benchmark run yet</div>
            ) : (
              <div className="flex flex-col gap-1">
                {runs.map((result, index) => (
                  <div
                    key={`${result.ranAt}-${index}`}
                    className="grid grid-cols-[1fr_auto_auto] items-center gap-2 rounded-md border border-line-soft bg-ink/50 px-2 py-1.5 text-[11px]"
                  >
                    <span className="text-mist">
                      {WORKLOADS[result.workload].label} · {compact(result.events)}
                    </span>
                    <span className="num text-mint">{compact(result.eventsPerSecond)}/s</span>
                    <span className="num text-fog">p99 {formatLatency(result.p99)}</span>
                  </div>
                ))}
              </div>
            )}
          </Panel>
        </div>

        <div className="flex flex-col gap-4">
          <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
            <StatTile
              label="throughput"
              value={latest ? `${compact(latest.eventsPerSecond)}/s` : '—'}
              sub={latest ? `${compact(latest.matchingEventsPerSecond)}/s matching only` : 'run a benchmark'}
              tone="mint"
            />
            <StatTile label="p50 latency" value={latest ? formatLatency(latest.p50) : '—'} />
            <StatTile label="p99 latency" value={latest ? formatLatency(latest.p99) : '—'} />
            <StatTile label="p99.9 latency" value={latest ? formatLatency(latest.p999) : '—'} />
          </div>

          <Panel
            title="Latency distribution"
            hint="log-linear histogram · browser timer resolution is ~1 µs"
          >
            <LatencyChart
              p50={latest?.p50 ?? 0}
              p99={latest?.p99 ?? 0}
              p999={latest?.p999 ?? 0}
              p9999={latest?.p9999 ?? 0}
              max={latest?.max ?? 0}
            />
          </Panel>

          <Panel title="Run detail" bodyClassName="p-0">
            <table className="w-full text-xs">
              <thead className="text-[10px] uppercase tracking-[0.12em] text-fog/70">
                <tr>
                  <th className="px-4 py-2 text-left font-medium">metric</th>
                  <th className="px-4 py-2 text-right font-medium">value</th>
                </tr>
              </thead>
              <tbody className="num">
                {[
                  ['events', latest ? formatInt(latest.events) : '—'],
                  ['trades produced', latest ? formatInt(latest.trades) : '—'],
                  ['engine rejects', latest ? formatInt(latest.rejected) : '—'],
                  ['resting orders after run', latest ? formatInt(latest.activeOrders) : '—'],
                  ['elapsed', latest ? formatDuration(latest.elapsedNs) : '—'],
                  ['p99.99 latency', latest ? formatLatency(latest.p9999) : '—'],
                  ['max latency', latest ? formatLatency(latest.max) : '—'],
                  ['mean latency', latest ? formatLatency(latest.mean) : '—'],
                  ['final CRC64', latest ? latest.crc64 : '—'],
                ].map(([label, value]) => (
                  <tr key={label} className="border-t border-line-soft/60">
                    <td className="px-4 py-1.5 text-fog">{label}</td>
                    <td className="px-4 py-1.5 text-right text-chalk">{value}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </Panel>
        </div>
      </div>

      <Panel
        title="Native reference run"
        hint="checked-in measurement from the Linux harness (reports/benchmark_results.json)"
        bodyClassName="p-0"
      >
        {native.runs.length === 0 ? (
          <div className="p-4 text-[11px] text-fog/70">
            No native results checked in yet — run <span className="num">make bench</span>.
          </div>
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full min-w-[760px] text-xs">
              <thead className="text-[10px] uppercase tracking-[0.12em] text-fog/70">
                <tr>
                  <th className="px-4 py-2 text-left font-medium">workload</th>
                  <th className="px-4 py-2 text-right font-medium">events</th>
                  <th className="px-4 py-2 text-right font-medium">M msg/s</th>
                  <th className="px-4 py-2 text-right font-medium">p50</th>
                  <th className="px-4 py-2 text-right font-medium">p99</th>
                  <th className="px-4 py-2 text-right font-medium">p99.9</th>
                  <th className="px-4 py-2 text-right font-medium">max</th>
                  <th className="px-4 py-2 text-right font-medium">heap allocs</th>
                </tr>
              </thead>
              <tbody className="num">
                {native.runs.slice(0, 9).map((run) => (
                  <tr key={`${run.workload}-${run.events}-${run.repeat}`} className="border-t border-line-soft/60">
                    <td className="px-4 py-1.5 text-mist">{run.workload}</td>
                    <td className="px-4 py-1.5 text-right text-fog">{compact(run.events)}</td>
                    <td className="px-4 py-1.5 text-right text-mint">
                      {(run.events_per_second / 1e6).toFixed(2)}
                    </td>
                    <td className="px-4 py-1.5 text-right">{formatDuration(run.latency_ns.p50)}</td>
                    <td className="px-4 py-1.5 text-right">{formatDuration(run.latency_ns.p99)}</td>
                    <td className="px-4 py-1.5 text-right">{formatDuration(run.latency_ns.p99_9)}</td>
                    <td className="px-4 py-1.5 text-right text-amber">
                      {formatDuration(run.latency_ns.max)}
                    </td>
                    <td className="px-4 py-1.5 text-right text-fog">{formatInt(run.heap_allocations)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
        <div className="grid gap-2 border-t border-line-soft px-4 py-3 text-[10px] leading-relaxed text-fog/70 sm:grid-cols-2">
          <div>
            <div className="mb-1 uppercase tracking-[0.12em] text-fog">environment</div>
            <div className="num">{String(native.environment?.cpu ?? 'unknown')}</div>
            <div className="num">
              {String(native.environment?.os ?? '')} · {String(native.environment?.logical_cores ?? '?')} cores
            </div>
            <div className="num">{String(native.environment?.compiler ?? '')}</div>
          </div>
          <div>
            <div className="mb-1 uppercase tracking-[0.12em] text-fog">honest caveats</div>
            <ul className="list-inside list-disc space-y-0.5">
              <li>Shared cloud runner: no CPU pinning, frequency scaling not controlled.</li>
              <li>Per-event samples include clock-read overhead.</li>
              <li>WASM and native numbers are separate measurements, not comparable.</li>
            </ul>
          </div>
        </div>
      </Panel>
    </div>
  );
}
